adpcmConvert:				;@ r0=adpcm data
;@----------------------------------------------------------------------------
	ldrb r1,adpcmOddEven
	eors r1,r1,#1
	strb r1,adpcmOddEven
	movne r0,r0,lsr#4

	movs r0,r0,lsl#29			;@ Check top bit (sign)
	mov r0,r0,lsr#29
	ldrb r1,adpcmIndex
	adr r2,msm5205Step
	add r2,r2,r1,lsl#3+1
	add r2,r2,r0,lsl#1
	ldrh r2,[r2]
	rsbcs r2,r2,#0

	adr r3,msm5205IndexShift
	ldrsb r3,[r3,r0]

	adds r1,r1,r3
	movmi r1,#0
	cmp r1,#48
	movpl r1,#48
	strb r1,adpcmIndex

	ldr r0,accumulator
	add r0,r0,r2,lsl#20
	str r0,accumulator
	mov r0,r0,asr#1
	orr r0,r0,r0,lsr#16

	bx lr
;@----------------------------------------------------------------------------

